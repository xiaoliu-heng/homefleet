// Generate notices from the modules used by Hub/Agent on every release target
// and from installed production npm packages. No private host paths are emitted.
import {execFileSync} from 'node:child_process';
import {readFileSync, readdirSync, existsSync, writeFileSync} from 'node:fs';
import {resolve, relative, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const go = process.env.GO || 'go';
const sections = [];
const licenseName = /^(unlicense|licen[cs]e|copying|copyright|notice)([-._].*)?$/i;
function licenseFiles(directory, depth = 0) {
  const files = [];
  for (const entry of readdirSync(directory, {withFileTypes: true}).sort((a,b) => a.name.localeCompare(b.name))) {
    const path = join(directory, entry.name);
    if (entry.isFile() && licenseName.test(entry.name)) files.push(path);
    if (entry.isDirectory() && depth > 0 && !['node_modules','.git'].includes(entry.name)) files.push(...licenseFiles(path, depth - 1));
  }
  return files;
}
function add(title, url, directory, files, label = '') {
  if (!files.length) throw new Error(`No license text found for ${title}; resolve before publishing.`);
  sections.push(`## ${title}\n\nSource: ${url}\n${label ? `\nDeclared license: ${label}\n` : ''}\n` + files.map(path => `### ${relative(directory,path).replaceAll('\\','/')}\n\n\`\`\`text\n${readFileSync(path,'utf8').replaceAll('\r\n','\n').replaceAll(/[ \t]+$/gm,'').trim()}\n\`\`\`\n`).join('\n'));
}
const goroot = execFileSync(go, ['env','GOROOT'], {cwd:root,encoding:'utf8'}).trim();
add('Go standard library and runtime','https://go.dev/LICENSE',goroot,[join(goroot,'LICENSE')],'BSD-3-Clause');
const modules = new Map();
for (const [os,arch] of [['linux','amd64'],['linux','arm64'],['darwin','arm64'],['windows','amd64']]) {
  const output = execFileSync(go,['list','-deps','-f','{{if .Module}}{{.Module.Path}}\t{{.Module.Version}}\t{{.Module.Dir}}{{end}}','./cmd/hub','./cmd/agent'],{cwd:root,env:{...process.env,GOOS:os,GOARCH:arch,CGO_ENABLED:'0'},encoding:'utf8'});
  for (const line of output.split('\n')) {
    const [name,version,dir] = line.split('\t');
    if (version && dir) modules.set(name,{version,dir});
  }
}
for (const [name,{version,dir}] of [...modules].sort(([a],[b]) => a.localeCompare(b))) {
  add(`${name} ${version}`,`https://pkg.go.dev/${name}@${version}`,dir,licenseFiles(dir));
}
const lock = JSON.parse(readFileSync(join(root,'web/package-lock.json'),'utf8'));
let npmCount = 0;
for (const [name,pkg] of Object.entries(lock.packages).sort(([a],[b]) => a.localeCompare(b))) {
  if (!name || pkg.dev || pkg.devOptional) continue;
  const dir = join(root,'web',name);
  if (!existsSync(dir)) throw new Error(`Install production dependency ${name} before generating notices.`);
  const packageInfo = JSON.parse(readFileSync(join(dir,'package.json'),'utf8'));
  const files = licenseFiles(dir,3);
  const extra = join(root,'licenses',packageInfo.name.replaceAll('/','_')+'.txt');
  if (existsSync(extra)) files.push(extra);
  // Use a stable label for supplemental upstream notices, never an absolute path.
  add(`${packageInfo.name} ${pkg.version}`,`https://www.npmjs.com/package/${packageInfo.name}/v/${pkg.version}`,dir,files,pkg.license || packageInfo.license || 'See text below');
  npmCount++;
}
let output = '# Third-party notices\n\nHomeFleet is licensed under MIT; third-party components retain their own licenses.\n\nThis file includes the Go runtime, Go modules linked on supported release targets, and production npm dependencies (including bundled vendor notices). Build-only dependencies are not redistributed in HomeFleet binaries. Generated by `node scripts/third-party-notices.mjs` after installing dependencies.\n\n' + sections.join('\n');
output = output.replaceAll(/### (?:\.\.\/)+licenses\//g, '### Supplemental upstream notice: ');
writeFileSync(join(root,'THIRD_PARTY_NOTICES.md'), output);
console.log(`Generated notices for ${modules.size} Go modules and ${npmCount} npm packages, plus the Go runtime.`);
